// Package mutate derives the grammar-oracle `derived` lane (Sprint 384,
// #1586): bounded deterministic mutants of required-positive fixtures
// (CONTRACT.md "Mutations (bounded, deterministic)") and source-mapped
// construct probes extracted from package-led Go units (plan lane "derived
// mixed probes"). Both earn no whole-unit credit and carry no authored
// expectation: their class is contextual with expected `-`, and the
// comparison driver compares the oracle with the reference.
//
// docs/grammar-oracle/derived.tsv is the generated row set, in the manifest's
// column schema. Its bytes are not committed: Generate rebuilds them from the
// frozen manifest inputs, and Materialize writes them where each row's source
// names them (tools/grammar-oracle/mutate/out/, ignored by git).
package mutate

import (
	"bytes"
	"crypto/sha256"
	"encoding/binary"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"math/rand/v2"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

// Frozen limits. The mutant ones are CONTRACT.md's; the probe ones are this
// package's and are recorded in the derived.tsv header.
const (
	Seed           = 384
	MaxParentBytes = 8192
	MaxPerFixture  = 8
	MaxMutants     = 4000
	MaxProbesUnit  = 8
	MaxProbeBytes  = 8192
	MaxProbes      = 1000

	// OutDir is where Materialize writes the derived inputs, relative to
	// the bashsharp-tests root; every row's source is tests:OutDir/<name>.
	OutDir = "tools/grammar-oracle/mutate/out"
)

// Tokens are CONTRACT.md's insertable tokens.
var Tokens = []string{"{", "}", "(", ")", "[", "]", ";", `"`, "'", "`", "\n", "~~~", ":=", "func", "@"}

// Parent is a manifest row with its resolved input bytes.
type Parent struct {
	ID, Lane, Source, SHA, Dialect, Policy, Class string
	Bytes                                         []byte
}

// Transform is the CONTRACT.md "Positions and transforms" record: each map
// entry is [out_start, orig_start, len]; out bytes outside the map are
// synthetic.
type Transform struct {
	Name string   `json:"name"`
	Map  [][3]int `json:"map"`
}

// Row is one derived.tsv row and its input bytes.
type Row struct {
	ID, Source, SHA, Dialect, Policy string
	Parent, Kind                     string
	Transform                        Transform
	Bytes                            []byte
}

// Name is the row's file name under OutDir.
func (r Row) Name() string { return unsafeName.ReplaceAllString(r.ID, "_") }

var unsafeName = regexp.MustCompile(`[^A-Za-z0-9._/-]`)

// TSV renders the row in the manifest column schema.
func (r Row) TSV() string {
	tr, err := json.Marshal(r.Transform)
	if err != nil {
		panic(err)
	}
	what := "mutant"
	if strings.HasPrefix(r.ID, "probe/") {
		what = "probe"
	}
	reason := fmt.Sprintf("%s of %s (%s); no authored expectation, oracle compared with reference; transform %s", what, r.Parent, r.Kind, tr)
	return strings.Join([]string{r.ID, "derived", r.Source, r.SHA, r.Dialect, r.Policy, "contextual", "-", "-", reason}, "\t")
}

// Header is derived.tsv's comment header.
const Header = `# Grammar-oracle derived inputs (Sprint 384, story #1586). GENERATED by
# tools/grammar-oracle/mutate (go test ./mutate -update); do not hand-edit. Schema: docs/grammar-oracle/CONTRACT.md
# Bytes are not committed: mutate.Materialize writes each source path. Positions refer to the derived bytes;
# the reason's transform maps them to the parent input ([out_start,orig_start,len]; unmapped bytes are synthetic).
# Mutants (CONTRACT.md): required-positive mixed and unit rows <= 8192 bytes in manifest order, PCG seed (384,
# sha256(fixture_id)[:8] big-endian), <= 8 per fixture, <= 4000 total, one edit each (delete, duplicate, swap,
# insert token). Kinds target boundaries first: start-insert, delete-closer, unbalance-quote, heredoc-delim,
# break-decorator, drop-semicolon, fence-width; remaining slots are random edits.
# Probes: top-level func/type/const/var/import declarations of unit-lane required-positive rows, verbatim,
# parsed as bashsharp; <= 8 per unit, <= 8192 bytes each, <= 1000 total. No whole-unit credit.
# fixture_id	lane	source	sha256	dialect	policy	class	expected	boundary	reason
`

// Generate derives every row from the manifest parents, in manifest order:
// all mutants, then all probes.
func Generate(parents []Parent) ([]Row, error) {
	var rows []Row
	seen := map[string]bool{}
	add := func(r Row) error {
		if seen[r.ID] || seen["name:"+r.Name()] {
			return fmt.Errorf("duplicate derived id or name %s", r.ID)
		}
		seen[r.ID], seen["name:"+r.Name()] = true, true
		h := sha256.Sum256(r.Bytes)
		r.SHA = hex.EncodeToString(h[:])
		r.Source = "tests:" + OutDir + "/" + r.Name()
		rows = append(rows, r)
		return nil
	}
	n := 0
	for _, p := range parents {
		if p.Class != "required-positive" || (p.Lane != "mixed" && p.Lane != "unit") || len(p.Bytes) > MaxParentBytes {
			continue
		}
		for _, r := range Mutants(p) {
			if n == MaxMutants {
				break
			}
			if err := add(r); err != nil {
				return nil, err
			}
			n++
		}
	}
	n = 0
	for _, p := range parents {
		if p.Class != "required-positive" || p.Lane != "unit" {
			continue
		}
		for _, r := range Probes(p) {
			if n == MaxProbes {
				break
			}
			if err := add(r); err != nil {
				return nil, err
			}
			n++
		}
	}
	return rows, nil
}

// edit is one CONTRACT.md edit at byte offset at.
type edit struct {
	op    string // delete, duplicate, swap, insert
	at    int
	token string
}

func (e edit) apply(src []byte) ([]byte, Transform) {
	n := len(src)
	var out []byte
	var m [][3]int
	name := e.op
	switch e.op {
	case "delete":
		out = append(append(out, src[:e.at]...), src[e.at+1:]...)
		m = [][3]int{{0, 0, e.at}, {e.at, e.at + 1, n - e.at - 1}}
	case "duplicate":
		out = append(append(out, src[:e.at+1]...), src[e.at:]...)
		m = [][3]int{{0, 0, e.at + 1}, {e.at + 1, e.at, n - e.at}}
	case "swap":
		out = append(append(append(out, src[:e.at]...), src[e.at+1], src[e.at]), src[e.at+2:]...)
		m = [][3]int{{0, 0, e.at}, {e.at, e.at + 1, 1}, {e.at + 1, e.at, 1}, {e.at + 2, e.at + 2, n - e.at - 2}}
	case "insert":
		out = append(append(append(out, src[:e.at]...), e.token...), src[e.at:]...)
		m = [][3]int{{0, 0, e.at}, {e.at + len(e.token), e.at, n - e.at}}
		name = "insert " + e.token
	}
	tr := Transform{Name: fmt.Sprintf("mutant %s at %d", name, e.at)}
	for _, s := range m {
		if s[2] > 0 {
			tr.Map = append(tr.Map, s)
		}
	}
	return out, tr
}

// rng is the CONTRACT.md PRNG for a fixture.
func rng(id string) *rand.Rand {
	h := sha256.Sum256([]byte(id))
	return rand.New(rand.NewPCG(Seed, binary.BigEndian.Uint64(h[:8])))
}

// Mutants returns at most MaxPerFixture mutants of p. Each boundary kind
// with a candidate site contributes one edit at a PRNG-chosen site, in the
// fixed kind order; random edits fill the remaining slots. A mutant equal to
// the parent or to an earlier mutant is skipped (bounded retries).
func Mutants(p Parent) []Row {
	r := rng(p.ID)
	src := p.Bytes
	var rows []Row
	have := map[string]bool{string(src): true}
	try := func(kind string, e edit) bool {
		out, tr := e.apply(src)
		if have[string(out)] {
			return false
		}
		have[string(out)] = true
		rows = append(rows, Row{
			ID: fmt.Sprintf("mutant/%s/%d", p.ID, len(rows)), Dialect: p.Dialect, Policy: p.Policy,
			Parent: p.ID, Kind: kind, Transform: tr, Bytes: out,
		})
		return true
	}
	for _, k := range kinds {
		if len(rows) == MaxPerFixture {
			return rows
		}
		if c := k.sites(src, p.Dialect); len(c) > 0 {
			try(k.name, c[r.IntN(len(c))])
		}
	}
	for attempt := 0; len(rows) < MaxPerFixture && attempt < 4*MaxPerFixture && len(src) > 1; attempt++ {
		e := edit{op: []string{"delete", "duplicate", "swap", "insert"}[r.IntN(4)], at: r.IntN(len(src) - 1)}
		if e.op == "insert" {
			e.token = Tokens[r.IntN(len(Tokens))]
		}
		try("random", e)
	}
	return rows
}

type kind struct {
	name  string
	sites func(src []byte, dialect string) []edit
}

var (
	startRe     = regexp.MustCompile(`(?m)^[ \t]*(func|type|const|var|import|if|for|while|until|case|select|switch|@|~~~|\{|\()`)
	fenceClose  = regexp.MustCompile(`(?m)^[ \t]*(~{3,})[ \t]*$`)
	fenceOpen   = regexp.MustCompile(`(?m)^[ \t]*(~{3,})[^~\n]`)
	heredocRe   = regexp.MustCompile(`<<-?[ \t]*['"]?([A-Za-z_][A-Za-z_0-9]*)['"]?`)
	decoratorRe = regexp.MustCompile(`(?m)^[ \t]*@[A-Za-z_][A-Za-z_0-9.]*(\()[^\n]*(\))[ \t]*$`)
)

// kinds are the boundary mutation kinds (each expressed as one CONTRACT edit).
var kinds = []kind{
	// Insert a token where a construct commits (a declaration, compound
	// command, decorator, fence or group start).
	{"start-insert", func(src []byte, _ string) []edit {
		var es []edit
		for i, m := range startRe.FindAllSubmatchIndex(src, -1) {
			es = append(es, edit{op: "insert", at: m[2], token: Tokens[i%len(Tokens)]})
		}
		return es
	}},
	// Delete a closing brace or one tilde of a fence closer.
	{"delete-closer", func(src []byte, _ string) []edit {
		var es []edit
		for i, b := range src {
			if b == '}' {
				es = append(es, edit{op: "delete", at: i})
			}
		}
		for _, m := range fenceClose.FindAllSubmatchIndex(src, -1) {
			es = append(es, edit{op: "delete", at: m[2]})
		}
		return es
	}},
	// Delete one quote character.
	{"unbalance-quote", func(src []byte, _ string) []edit {
		var es []edit
		for i, b := range src {
			if b == '"' || b == '\'' || b == '`' {
				es = append(es, edit{op: "delete", at: i})
			}
		}
		return es
	}},
	// Duplicate the first byte of a here-document's terminator line.
	{"heredoc-delim", func(src []byte, _ string) []edit {
		var es []edit
		for _, m := range heredocRe.FindAllSubmatchIndex(src, -1) {
			word := src[m[2]:m[3]]
			nl := bytes.IndexByte(src[m[1]:], '\n')
			if nl < 0 {
				continue
			}
			for off := m[1] + nl + 1; off < len(src); {
				end := bytes.IndexByte(src[off:], '\n')
				if end < 0 {
					end = len(src) - off
				}
				if line := bytes.TrimLeft(src[off:off+end], "\t"); bytes.Equal(line, word) {
					es = append(es, edit{op: "duplicate", at: off + end - len(word)})
					break
				}
				off += end + 1
			}
		}
		return es
	}},
	// Delete the opening or closing parenthesis of a decorator call.
	{"break-decorator", func(src []byte, _ string) []edit {
		var es []edit
		for _, m := range decoratorRe.FindAllSubmatchIndex(src, -1) {
			es = append(es, edit{op: "delete", at: m[2]}, edit{op: "delete", at: m[4]})
		}
		return es
	}},
	// Delete the newline that inserts a Go semicolon at the end of a
	// statement line, joining it to the next statement.
	{"drop-semicolon", func(src []byte, dialect string) []edit {
		if dialect == "bash" {
			return nil
		}
		var es []edit
		for i := 1; i+1 < len(src); i++ {
			if src[i] != '\n' || src[i+1] == '\n' {
				continue
			}
			if b := src[i-1]; b == ')' || b == ']' || b == '}' || b == '"' || b == '`' ||
				b == '_' || b >= '0' && b <= '9' || b >= 'a' && b <= 'z' || b >= 'A' && b <= 'Z' {
				es = append(es, edit{op: "delete", at: i})
			}
		}
		return es
	}},
	// Widen a fence opener or closer by one tilde.
	{"fence-width", func(src []byte, _ string) []edit {
		var es []edit
		for _, re := range []*regexp.Regexp{fenceOpen, fenceClose} {
			for _, m := range re.FindAllSubmatchIndex(src, -1) {
				es = append(es, edit{op: "duplicate", at: m[2]})
			}
		}
		return es
	}},
}

var declRe = regexp.MustCompile(`^(func|type|const|var|import)[ \t(]`)

// Probes extracts p's top-level declarations verbatim (gofmt layout: a
// declaration whose first line opens a brace or parenthesis ends at the
// next column-0 closer line), at most MaxProbesUnit of at most MaxProbeBytes.
func Probes(p Parent) []Row {
	src := p.Bytes
	var rows []Row
	var lines []int // line start offsets
	for off := 0; off < len(src); {
		lines = append(lines, off)
		nl := bytes.IndexByte(src[off:], '\n')
		if nl < 0 {
			break
		}
		off += nl + 1
	}
	end := func(i int) int { // end offset (after LF) of line i
		if i+1 < len(lines) {
			return lines[i+1]
		}
		return len(src)
	}
	for i := 0; i < len(lines) && len(rows) < MaxProbesUnit; i++ {
		line := src[lines[i]:end(i)]
		m := declRe.FindSubmatch(line)
		if m == nil {
			continue
		}
		j := i
		if t := bytes.TrimRight(line, " \t\n"); bytes.HasSuffix(t, []byte("{")) || bytes.HasSuffix(t, []byte("(")) {
			closer := []byte("}")
			if t[len(t)-1] == '(' {
				closer = []byte(")")
			}
			for j = i + 1; j < len(lines) && !bytes.Equal(bytes.TrimRight(src[lines[j]:end(j)], "\n"), closer); j++ {
			}
			if j == len(lines) {
				continue
			}
		}
		start, stop := lines[i], end(j)
		if stop-start > MaxProbeBytes {
			continue
		}
		rows = append(rows, Row{
			ID: fmt.Sprintf("probe/%s/%d", p.ID, len(rows)), Dialect: "bashsharp", Policy: "sh-syntax",
			Parent: p.ID, Kind: string(m[1]),
			Transform: Transform{Name: fmt.Sprintf("extract %s declaration, lines %d-%d", m[1], i+1, j+1), Map: [][3]int{{0, start, stop - start}}},
			Bytes:     bytes.Clone(src[start:stop]),
		})
		i = j
	}
	return rows
}

// Render is derived.tsv's exact content.
func Render(rows []Row) []byte {
	var b bytes.Buffer
	b.WriteString(Header)
	for _, r := range rows {
		b.WriteString(r.TSV() + "\n")
	}
	return b.Bytes()
}

// Materialize writes every row's bytes under root/OutDir, replacing it.
func Materialize(root string, rows []Row) error {
	dir := filepath.Join(root, OutDir)
	if err := os.RemoveAll(dir); err != nil {
		return err
	}
	for _, r := range rows {
		path := filepath.Join(dir, filepath.FromSlash(r.Name()))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(path, r.Bytes, 0o644); err != nil {
			return err
		}
	}
	return nil
}
